// @vitest-environment node
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { analytics } from '@/lib/server/analytics';
import { PermanentError } from '@/lib/server/errors';
// Runs only against a live analytics service: ANALYTICS_URL + ANALYTICS_SERVICE_TOKEN.
const live = !!process.env.ANALYTICS_URL;
describe.skipIf(!live)('analytics service (live)', () => {
  it('parses a FIT fixture generated by the official SDK', async () => {
    const bytes = readFileSync(
      new URL('./fixtures/straight-3600m.fit', import.meta.url),
    );
    const out = await analytics<{
      summary: { distance_m: number };
      utc_offset_s: number;
    }>('/v1/activities/parse?format=fit', {
      method: 'POST',
      body: bytes,
      headers: { 'Content-Type': 'application/octet-stream' },
    });
    expect(out.summary.distance_m).toBeCloseTo(3600, -1);
    expect(out.utc_offset_s).toBe(-21600);
  });
  it('maps malformed files to a permanent error', async () => {
    await expect(
      analytics('/v1/activities/parse?format=fit', {
        method: 'POST',
        body: 'nope',
      }),
    ).rejects.toBeInstanceOf(PermanentError);
  });
});
